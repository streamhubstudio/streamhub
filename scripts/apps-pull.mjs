#!/usr/bin/env node
/**
 * apps-pull.mjs — compose the decoupled Studio Apps INTO the build
 * (internal design notes §4). Reads the committed `apps.lock.json`,
 * downloads each pinned package, VERIFIES its sha256 against the lock (fail
 * closed), extracts it to `vendor/apps/<id>/` (gitignored), then LINKS the parts
 * into the two auto-discovery paths so the existing registries pick them up
 * unchanged:
 *
 *   backend  → streamhub-core/src/plugins-vendor/<id>/streamhub.app.json
 *              + <id>/worker/** (declarative manifest + the Python worker
 *              source COPIED INSIDE the core tree; `worker.workerDir` stays
 *              PACKAGE-RELATIVE and the registry resolves it against the
 *              package dir — so the composed core is fully PORTABLE: the
 *              deploy tarball / docker COPY / `nest build` assets carry the
 *              vendored apps wherever the core goes, no absolute host paths)
 *   frontend → streamhub-web/src/plugins-vendor/<id>/**  (TS source; single-`../`
 *              framework imports rewritten to resolve from the vendor dir)
 *
 * Both `-vendor` dirs are gitignored and regenerated by this script. On an id
 * that ALSO exists in-tree, the registries keep the in-tree copy and skip the
 * vendored one — this script just links; it warns when it detects the shadow.
 *
 * Sources per lock entry (`source` or `repo`):
 *   file:./path             a local tarball (F0 pilot / offline builds)
 *   https://…               a direct URL to a tarball
 *   gitlab:group/project    a private GitLab release asset (STREAMHUB_APPS_TOKEN)
 */
import fs from 'node:fs'
import path from 'node:path'
import zlib from 'node:zlib'
import {
  REPO_ROOT,
  freshDir,
  readLock,
  rewriteVendorImports,
  sha256,
} from './lib/appcompose.mjs'
import { extractTarGz } from './lib/tar.mjs'

const VENDOR_APPS = path.join(REPO_ROOT, 'vendor', 'apps')
const CORE_VENDOR = path.join(REPO_ROOT, 'streamhub-core', 'src', 'plugins-vendor')
const WEB_VENDOR = path.join(REPO_ROOT, 'streamhub-web', 'src', 'plugins-vendor')

const REWRITE_EXT = new Set(['.ts', '.tsx', '.js', '.jsx'])

function log(msg) {
  console.log(`apps-pull: ${msg}`)
}
function die(msg) {
  console.error(`apps-pull: ${msg}`)
  process.exit(1)
}

/** Resolve the package bytes for a lock entry from its source. */
async function fetchPackage(entry) {
  const src = entry.source ?? entry.repo ?? ''
  if (src.startsWith('file:')) {
    const rel = src.slice('file:'.length).replace(/^\.\//, '')
    const abs = path.resolve(REPO_ROOT, rel)
    if (!fs.existsSync(abs)) die(`${entry.id}: local package not found: ${rel}`)
    return fs.readFileSync(abs)
  }
  if (src.startsWith('http://') || src.startsWith('https://')) {
    return fetchUrl(src)
  }
  if (src.startsWith('gitlab:')) {
    return fetchGitlabAsset(src.slice('gitlab:'.length), entry, process.env.STREAMHUB_APPS_TOKEN)
  }
  die(`${entry.id}: unsupported source '${src}' (use file:, https:// or gitlab:)`)
}

async function fetchUrl(url, headers = {}) {
  const res = await fetch(url, { headers })
  if (!res.ok) die(`download failed (${res.status}) for ${url}`)
  return Buffer.from(await res.arrayBuffer())
}

/**
 * Fetch a private GitLab package bundle. `repoPath` = group/project; the asset
 * is `streamhub-app-<id>-<version>.tar.gz` in the generic package registry at
 * `.../packages/generic/streamhub-app-<id>/<version>/<file>`.
 *
 * The DETERMINISTIC package URL means no `read_api` call is needed, so a
 * least-privilege **read-only deploy token** (`read_package_registry`) is
 * enough — that's what ships as the CI/deploy `STREAMHUB_APPS_TOKEN`. A deploy
 * token (`gldt-…`) authenticates with the `Deploy-Token` header; a personal
 * access token (`glpat-…`, handy for local dev) uses `PRIVATE-TOKEN`.
 */
async function fetchGitlabAsset(repoPath, entry, token) {
  if (!token) die(`${entry.id}: STREAMHUB_APPS_TOKEN unset — cannot fetch gitlab package`)
  const host = process.env.STREAMHUB_APPS_GITLAB_HOST ?? 'https://gitlab.com'
  const proj = encodeURIComponent(repoPath)
  const file = `streamhub-app-${entry.id}-${entry.version}.tar.gz`
  const headers = token.startsWith('gldt-')
    ? { 'Deploy-Token': token }
    : { 'PRIVATE-TOKEN': token }
  const url = `${host}/api/v4/projects/${proj}/packages/generic/streamhub-app-${entry.id}/${entry.version}/${file}`
  return fetchUrl(url, headers)
}

/** Recursive plain copy (no import rewriting — worker sources ship verbatim). */
function copyTree(absSrc, absDest) {
  fs.mkdirSync(absDest, { recursive: true })
  for (const d of fs.readdirSync(absSrc, { withFileTypes: true })) {
    const s = path.join(absSrc, d.name)
    const t = path.join(absDest, d.name)
    if (d.isDirectory()) copyTree(s, t)
    else if (d.isFile()) fs.copyFileSync(s, t)
  }
}

/**
 * Link the extracted package's backend into the core vendor dir: the manifest
 * VERBATIM (worker.workerDir stays package-relative — the registry resolves it
 * against the package dir via synthesizeMeta's `packageDir`) plus the worker
 * source tree copied ALONGSIDE it. Everything the composed core needs at
 * runtime therefore lives INSIDE streamhub-core/src/plugins-vendor/<id>/ and
 * travels with the core (deploy tarball, docker COPY, `nest build` assets →
 * dist/plugins-vendor). No absolute host paths are ever baked in.
 */
function linkBackend(id, pkgDir) {
  const manifestPath = path.join(pkgDir, 'streamhub.app.json')
  if (!fs.existsSync(manifestPath)) die(`${id}: package is missing streamhub.app.json`)
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'))

  const dest = path.join(CORE_VENDOR, id)
  freshDir(dest)
  fs.writeFileSync(path.join(dest, 'streamhub.app.json'), JSON.stringify(manifest, null, 2) + '\n')
  if (manifest.worker && manifest.worker.needsWorker) {
    const rel = manifest.worker.workerDir ?? 'worker'
    if (path.isAbsolute(rel)) die(`${id}: manifest worker.workerDir must be package-relative, got '${rel}'`)
    const workerSrc = path.join(pkgDir, rel)
    if (!fs.existsSync(workerSrc)) die(`${id}: package worker dir '${rel}' missing`)
    copyTree(workerSrc, path.join(dest, rel))
  }
}

/** Link the extracted package's frontend source into the web vendor dir. */
function linkFrontend(id, pkgDir) {
  const src = path.join(pkgDir, 'frontend')
  if (!fs.existsSync(src)) return false
  const dest = path.join(WEB_VENDOR, id)
  freshDir(dest)
  const walk = (absSrc, absDest) => {
    for (const d of fs.readdirSync(absSrc, { withFileTypes: true })) {
      const s = path.join(absSrc, d.name)
      const t = path.join(absDest, d.name)
      if (d.isDirectory()) {
        fs.mkdirSync(t, { recursive: true })
        walk(s, t)
      } else if (d.isFile()) {
        if (REWRITE_EXT.has(path.extname(d.name))) {
          fs.writeFileSync(t, rewriteVendorImports(fs.readFileSync(s, 'utf8')))
        } else {
          fs.copyFileSync(s, t)
        }
      }
    }
  }
  walk(src, dest)
  return true
}

async function main() {
  const lock = readLock()
  if (lock.length === 0) {
    log('apps.lock.json is empty — nothing to compose')
    return
  }
  fs.mkdirSync(VENDOR_APPS, { recursive: true })
  fs.mkdirSync(CORE_VENDOR, { recursive: true })
  fs.mkdirSync(WEB_VENDOR, { recursive: true })

  for (const entry of lock) {
    if (!entry.id || !entry.version || !entry.sha256) {
      die(`invalid lock entry (needs id, version, sha256): ${JSON.stringify(entry)}`)
    }
    log(`composing ${entry.id}@${entry.version}…`)
    const gz = await fetchPackage(entry)
    // Verify the CONTENT hash — sha256 of the UNCOMPRESSED tar, NOT the .tar.gz.
    // gzip is not reproducible across zlib versions/platforms: a re-run release
    // pipeline re-uploads a byte-identical tar wrapped in different gzip bytes,
    // which would flip a gzip-hash lock and break the build. The tar itself is
    // deterministic (ci/pack.mjs sorts entries + zeroes mtime), so hashing it
    // keeps the lock stable. See https://streamhub.studio/docs/development/PACKAGE-FORMAT.
    const tar = zlib.gunzipSync(gz)
    const digest = sha256(tar)
    if (digest !== entry.sha256) {
      die(`${entry.id}: content sha256 MISMATCH — lock ${entry.sha256.slice(0, 12)}…, got ${digest.slice(0, 12)}… (refusing)`)
    }

    const pkgDir = path.join(VENDOR_APPS, entry.id)
    freshDir(pkgDir)
    extractTarGz(gz, pkgDir)

    linkBackend(entry.id, pkgDir)
    const hasFrontend = linkFrontend(entry.id, pkgDir)

    // Precedence note: an in-tree app of the same id WINS; the vendored copy is
    // linked but the registries will skip it. Surface that so it's never a
    // silent no-op during the F0 pilot. The core registry keys on a compiled
    // `plugin.meta.{ts,js}` (NOT the folder), so a folder that holds only the
    // authored `streamhub.app.json` (like the vendorized lpr pilot) does NOT
    // shadow — the vendored package is the live one.
    const inTreeCore = ['plugin.meta.ts', 'plugin.meta.js'].some((f) =>
      fs.existsSync(path.join(REPO_ROOT, 'streamhub-core', 'src', 'plugins', entry.id, f)),
    )
    const shadow = inTreeCore ? '  (shadowed by in-tree app — registries keep the in-tree copy)' : ''
    log(`  ✓ ${entry.id}: backend linked${hasFrontend ? ' + frontend' : ''}${shadow}`)
  }
  log(`composed ${lock.length} app(s) into vendor/`)
}

main().catch((e) => die(e.stack || e.message))
