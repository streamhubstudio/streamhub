#!/usr/bin/env node
/**
 * Assemble the committed, downloadable EXAMPLE bundles into `examples/`.
 *
 * These are the GENERIC (placeholder-configured) bundles — each is a
 * self-contained folder (`index.html` + `config.js` + `README.md`) a user drops
 * on any static host and points at their own StreamHub by editing `config.js`.
 * They are generated from the EXACT same source as the server-rendered
 * `/samples` pages and the per-app download endpoint (no logic fork):
 * `streamhub-core/src/modules/samples/example-bundle.ts`.
 *
 * Because the source is TypeScript with extensionless imports, this generator
 * consumes the COMPILED output — build the core first:
 *
 *   (cd streamhub-core && npm run build)
 *   node scripts/build-examples.mjs
 *
 * or simply `npm run build:examples` from `streamhub-core/`.
 *
 * Output:
 *   examples/<id>/{index.html,config.js,README.md}   (committed)
 *   examples/README.md                               (committed)
 *   examples/dist/<id>.zip, examples/dist/streamhub-examples.zip (gitignored)
 */
import { mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '..');
const distDir = resolve(repo, 'streamhub-core/dist/modules/samples');

async function importDist(name) {
  const p = join(distDir, name);
  return import(pathToFileURL(p).href);
}

let bundle, zip;
try {
  bundle = await importDist('example-bundle.js');
  zip = await importDist('zip.js');
} catch (e) {
  console.error(
    'Could not import the compiled example builder. Build the core first:\n' +
      '  (cd streamhub-core && npm run build)\n',
  );
  console.error(String((e && e.message) || e));
  process.exit(1);
}

const { EXAMPLE_BUNDLES, buildExampleBundle, PLACEHOLDER_CONTEXT } = bundle;
const { createZip } = zip;

const examplesRoot = resolve(repo, 'examples');
const zipsDir = join(examplesRoot, 'dist');

// Fresh start (keep nothing stale). The .gitignore below re-creates itself.
rmSync(examplesRoot, { recursive: true, force: true });
mkdirSync(zipsDir, { recursive: true });

const combined = [];
for (const d of EXAMPLE_BUNDLES) {
  const { files } = buildExampleBundle(d.id, PLACEHOLDER_CONTEXT);
  const dir = join(examplesRoot, d.id);
  mkdirSync(dir, { recursive: true });
  for (const [name, content] of Object.entries(files)) {
    writeFileSync(join(dir, name), content, 'utf8');
    combined.push({ name: `${d.id}/${name}`, data: content });
  }
  // Per-example zip (regenerable; gitignored).
  const entries = Object.entries(files).map(([name, data]) => ({ name, data }));
  writeFileSync(join(zipsDir, `${d.id}.zip`), createZip(entries));
}

// Root README + combined zip.
const rootReadme = `# StreamHub examples

Self-contained, statically-hostable examples for StreamHub. Each folder is
independent: edit its \`config.js\` (set \`baseUrl\`, \`wsUrl\`, \`app\`, \`room\` to
your StreamHub), then host the folder on any static host — S3, Netlify, nginx,
GitHub Pages — or open \`index.html\` locally. No build step.

These bundles ship with **placeholder** config; the dashboard's per-app download
(GET /apps/:app/examples/:id.zip) hands you the same bundle already wired to a
specific app.

## Examples

${EXAMPLE_BUNDLES.map((d) => `- **${d.id}/** — ${d.title}: ${d.description}`).join('\n')}

Generated by \`scripts/build-examples.mjs\` from
\`streamhub-core/src/modules/samples/example-bundle.ts\` — do not edit by hand.
`;
writeFileSync(join(examplesRoot, 'README.md'), rootReadme, 'utf8');
combined.unshift({ name: 'README.md', data: rootReadme });
writeFileSync(join(zipsDir, 'streamhub-examples.zip'), createZip(combined));

// Keep the regenerable zips out of git.
writeFileSync(join(examplesRoot, '.gitignore'), 'dist/\n', 'utf8');

console.log(
  `Wrote ${EXAMPLE_BUNDLES.length} example bundle(s) to examples/ ` +
    `(+ zips in examples/dist/).`,
);
