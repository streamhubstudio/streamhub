package samples

import (
	"os"
	"path/filepath"
	"testing"
)

// The committed examples/ must be exactly what build-examples generates.
func TestCommittedExamplesUpToDate(t *testing.T) {
	root := filepath.Join("..", "..", "..", "examples")
	if _, err := os.Stat(root); err != nil {
		t.Skip("examples/ not present (out-of-repo build)")
	}
	want := ExampleTree()
	for path, content := range want {
		got, err := os.ReadFile(filepath.Join(root, path))
		if err != nil {
			t.Errorf("%s: %v — run `go generate ./cmd/build-examples`", path, err)
			continue
		}
		if string(got) != content {
			t.Errorf("examples/%s is stale — run `go generate ./cmd/build-examples`", path)
		}
	}
	// No stray committed files beyond the generated set.
	_ = filepath.WalkDir(root, func(p string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			if d != nil && d.IsDir() && d.Name() == "dist" {
				return filepath.SkipDir
			}
			return err
		}
		rel, _ := filepath.Rel(root, p)
		if _, ok := want[filepath.ToSlash(rel)]; !ok {
			t.Errorf("examples/%s is not generated by build-examples", rel)
		}
		return nil
	})
}

func TestWriteExamples(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "examples")
	if err := WriteExamples(dir); err != nil {
		t.Fatal(err)
	}
	for path, content := range ExampleTree() {
		got, err := os.ReadFile(filepath.Join(dir, path))
		if err != nil || string(got) != content {
			t.Errorf("%s not written as generated (%v)", path, err)
		}
	}
	for _, d := range append(ExampleBundles, ExampleDescriptor{ID: "streamhub-examples"}) {
		if fi, err := os.Stat(filepath.Join(dir, "dist", d.ID+".zip")); err != nil || fi.Size() == 0 {
			t.Errorf("dist/%s.zip missing", d.ID)
		}
	}
}
