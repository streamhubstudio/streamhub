package samples

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// ExamplesReadme is the root examples/README.md of the committed bundles.
func ExamplesReadme() string {
	var list strings.Builder
	for i, d := range ExampleBundles {
		if i > 0 {
			list.WriteString("\n")
		}
		fmt.Fprintf(&list, "- **%s/** — %s: %s", d.ID, d.Title, d.Description)
	}
	return "# StreamHub examples\n\n" +
		"Self-contained, statically-hostable examples for StreamHub. Each folder is\n" +
		"independent: edit its `config.js` (set `baseUrl`, `wsUrl`, `app`, `room` to\n" +
		"your StreamHub), then host the folder on any static host — S3, Netlify, nginx,\n" +
		"GitHub Pages — or open `index.html` locally. No build step.\n\n" +
		"These bundles ship with **placeholder** config; the dashboard's per-app download\n" +
		"(GET /apps/:app/examples/:id.zip) hands you the same bundle already wired to a\n" +
		"specific app.\n\n" +
		"## Examples\n\n" + list.String() + "\n\n" +
		"Generated by `go generate ./cmd/build-examples` (streamhub-core-go) from\n" +
		"`internal/samples` — do not edit by hand.\n"
}

// ExampleTree is every committed file of examples/ (path → content),
// generated with PlaceholderContext. The zips under dist/ are not included.
func ExampleTree() map[string]string {
	out := map[string]string{"README.md": ExamplesReadme(), ".gitignore": "dist/\n"}
	for _, b := range BuildAllBundles(nil) {
		for _, f := range b.Files {
			out[b.ID+"/"+f.Name] = f.Data
		}
	}
	return out
}

// WriteExamples regenerates root (the repo's examples/): the committed
// bundles + README, and the gitignored per-example and combined zips in
// dist/. Stale content is removed first.
func WriteExamples(root string) error {
	if err := os.RemoveAll(root); err != nil {
		return err
	}
	dist := filepath.Join(root, "dist")
	if err := os.MkdirAll(dist, 0o755); err != nil {
		return err
	}
	readme := ExamplesReadme()
	combined := []ZipEntry{{Name: "README.md", Data: []byte(readme)}}
	for _, b := range BuildAllBundles(nil) {
		dir := filepath.Join(root, b.ID)
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
		entries := make([]ZipEntry, 0, len(b.Files))
		for _, f := range b.Files {
			if err := os.WriteFile(filepath.Join(dir, f.Name), []byte(f.Data), 0o644); err != nil {
				return err
			}
			entries = append(entries, ZipEntry{f.Name, []byte(f.Data)})
			combined = append(combined, ZipEntry{b.ID + "/" + f.Name, []byte(f.Data)})
		}
		if err := os.WriteFile(filepath.Join(dist, b.ID+".zip"), CreateZip(entries), 0o644); err != nil {
			return err
		}
	}
	if err := os.WriteFile(filepath.Join(root, "README.md"), []byte(readme), 0o644); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dist, "streamhub-examples.zip"), CreateZip(combined), 0o644); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(root, ".gitignore"), []byte("dist/\n"), 0o644)
}
