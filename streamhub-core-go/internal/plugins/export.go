// PackTar builds the uncompressed USTAR stream (mtime/uid/gid fixed at 0).
func PackTar(entries []TarEntry) ([]byte, error) {
	var buf bytes.Buffer
	for _, e := range entries {
		h, err := tarHeader(e)
		if err != nil {
			return nil, err
		}
		buf.Write(h)
		buf.Write(e.Body)
		if rem := len(e.Body) % 512; rem != 0 {
			buf.Write(make([]byte, 512-rem))
		}
	}
	buf.Write(make([]byte, 1024))
	return buf.Bytes(), nil
}

// PackTarGz is PackTar + gzip (best compression).
func PackTarGz(entries []TarEntry) ([]byte, error) {
	tar, err := PackTar(entries)
	if err != nil {
		return nil, err
	}
	var out bytes.Buffer
	zw, _ := gzip.NewWriterLevel(&out, gzip.BestCompression)
	_, _ = zw.Write(tar)
	if err := zw.Close(); err != nil {
		return nil, err
	}
	return out.Bytes(), nil
}

func writeOctal(h []byte, off, length int, value int64) {
	s := strconv.FormatInt(value, 8)
	for len(s) < length-1 {
		s = "0" + s
	}
	copy(h[off:off+length-1], s)
	h[off+length-1] = 0
}

// writeStr is Buffer#write(s, off, max, 'utf8'): never splits a character.
func writeStr(h []byte, off, maxLen int, s string) {
	n := 0
	for _, r := range s {
		w := len(string(r))
		if n+w > maxLen {
			break
		}
		n += w
	}
	copy(h[off:off+n], s[:n])
}

func tarHeader(e TarEntry) ([]byte, error) {
	h := make([]byte, 512)
	name, prefix, err := splitTarName(e.Name)
	if err != nil {
		return nil, err
	}
	writeStr(h, 0, 100, name)
	mode := e.Mode
	if mode == 0 {
		mode = 0o644
	}
	writeOctal(h, 100, 8, int64(mode))
	writeOctal(h, 108, 8, 0)
	writeOctal(h, 116, 8, 0)
	writeOctal(h, 124, 12, int64(len(e.Body)))
	writeOctal(h, 136, 12, 0)
	copy(h[148:156], "        ")
	h[156] = '0'
	copy(h[257:263], "ustar\x00")
	copy(h[263:265], "00")
	if prefix != "" {
		writeStr(h, 345, 155, prefix)
	}
	sum := 0
	for _, b := range h {
		sum += int(b)
	}
	cs := strconv.FormatInt(int64(sum), 8)
	for len(cs) < 6 {
		cs = "0" + cs
	}
	copy(h[148:154], cs)
	h[154] = 0
	h[155] = ' '
	return h, nil
}

func splitTarName(full string) (string, string, error) {
	if len(full) <= 100 {
		return full, "", nil
	}
	parts := strings.Split(full, "/")
	for i := 0; i < len(parts)-1; i++ {
		prefix, name := strings.Join(parts[:i+1], "/"), strings.Join(parts[i+1:], "/")
		if len(name) <= 100 && len(prefix) <= 155 {
			return name, prefix, nil
		}
	}
	return "", "", fmt.Errorf("path too long for tar: %s", full)
}
