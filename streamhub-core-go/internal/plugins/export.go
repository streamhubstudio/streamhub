// ResolveWorkerDir finds a worker SOURCE dir: the vendored package's own
// worker (pluginID given) → $STREAMHUB_WORKER_SRC_ROOT/<dir> →
// /opt/worker-src/<dir> → <repo>/<dir>. "" when none exists.
func ResolveWorkerDir(workerDir, pluginID string, paths Paths, env func(string) string) string {
	var candidates []string
	if pluginID != "" {
		candidates = append(candidates, filepath.Join(paths.VendorRoot, pluginID, "worker"))
	}
	if root := env("STREAMHUB_WORKER_SRC_ROOT"); root != "" {
		candidates = append(candidates, filepath.Join(root, workerDir))
	}
	candidates = append(candidates, filepath.Join("/opt/worker-src", workerDir))
	if paths.RepoRoot != "" {
		candidates = append(candidates, filepath.Join(paths.RepoRoot, workerDir))
	}
	for _, c := range candidates {
		if st, err := os.Stat(c); err == nil && st.IsDir() {
			return c
		}
	}
	return ""
}

func resolveRepoLicense(srcDir string, paths Paths, env func(string) string) []byte {
	var candidates []string
	if root := env("STREAMHUB_WORKER_SRC_ROOT"); root != "" {
		candidates = append(candidates, filepath.Join(root, "LICENSE"))
	}
	candidates = append(candidates, "/opt/worker-src/LICENSE", filepath.Join(srcDir, "..", "LICENSE"))
	if paths.RepoRoot != "" {
		candidates = append(candidates, filepath.Join(paths.RepoRoot, "LICENSE"))
	}
	for _, c := range candidates {
		if st, err := os.Stat(c); err == nil && st.Mode().IsRegular() && st.Size() <= maxBundleFileBytes {
			if b, err := os.ReadFile(c); err == nil {
				return b
			}
		}
	}
	return nil
}

