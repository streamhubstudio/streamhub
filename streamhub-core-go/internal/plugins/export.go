// Port of plugin-export.service.ts: the Studio-App exporter. The bundle is
// built by calling the meta's pure spawn with a SYNTHETIC context, so no live
// token / host / secret is ever embedded. Packed with a deterministic USTAR
// writer (mtime/uid/gid 0): the uncompressed tar is byte-identical to Node's
// (the gzip framing may differ by encoder).

// TarEntry is one bundle file.
type TarEntry struct {
	Name string
	Body []byte
	Mode int // 0 = 0o644
}

const (
	placeholderApp        = "myapp"
	placeholderPublicBase = "https://your-streamhub.example.com"
	placeholderLivekit    = "wss://your-streamhub.example.com:7880"
	maxBundleFileBytes    = 5 * 1024 * 1024
)

var excludedDirs = set("__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache", ".git", ".venv",
	"venv", "env", "node_modules", ".idea", ".vscode", "build", "dist")

var (
	compiledPy  = regexp.MustCompile(`\.py[cod]$`)
	sqliteFile  = regexp.MustCompile(`\.db(-journal|-wal|-shm)?$`)
	secretKeyRe = regexp.MustCompile(`(?i)secret|token|password|passwd|credential|api[_-]?key|apikey|private[_-]?key`)
)

func isExcludedFile(name string) bool {
	return name == ".DS_Store" || compiledPy.MatchString(name) || sqliteFile.MatchString(name)
}

// syntheticCtx is the placeholder spawn context of the exporter.
func syntheticCtx(meta *Meta) WorkerContext {
	return WorkerContext{
		App: placeholderApp, Config: DefaultConfig(meta),
		AppDir: "/data/apps/" + placeholderApp, DataDir: "/data", LivekitURL: placeholderLivekit,
	}
}

// deriveModule is the `python -m <module>` of the spawn args.
func deriveModule(args []string, id string) string {
	for i, a := range args {
		if a == "-m" && i+1 < len(args) && args[i+1] != "" {
			return args[i+1]
		}
		if a == "-m" {
			break
		}
	}
	return strings.ReplaceAll(id, "-", "_") + "_worker"
}

// ComposeBundle lists the bundle entries for meta given its worker source.
func ComposeBundle(meta *Meta, id, srcDir string, paths Paths, env func(string) string) ([]TarEntry, error) {
	spec := meta.Worker.Spawn(syntheticCtx(meta))
	module := deriveModule(spec.Args, id)
	entries, err := collectWorkerFiles(srcDir, id)
	if err != nil {
		return nil, err
	}
	entries = append(entries,
		TarEntry{Name: id + "/Dockerfile", Body: []byte(generateDockerfile(module))},
		TarEntry{Name: id + "/docker-compose.yml", Body: []byte(generateCompose(id))},
		TarEntry{Name: id + "/.env.example", Body: []byte(generateEnvExample(meta, id, spec.Env, env))},
		TarEntry{Name: id + "/README.md", Body: []byte(generateReadme(meta, id, module, spec.Env))},
	)
	if lic := resolveRepoLicense(srcDir, paths, env); lic != nil {
		entries = append(entries, TarEntry{Name: id + "/LICENSE", Body: lic})
	}
	return entries, nil
}

func collectWorkerFiles(srcDir, id string) ([]TarEntry, error) {
	var out []TarEntry
	var walk func(abs, rel string) error
	walk = func(abs, rel string) error {
		dirents, err := os.ReadDir(abs)
		if err != nil {
			return err
		}
		sort.SliceStable(dirents, func(i, j int) bool { return localeCompare(dirents[i].Name(), dirents[j].Name()) < 0 })
		for _, d := range dirents {
			name := d.Name()
			switch {
			case d.IsDir():
				if excludedDirs[name] || strings.HasSuffix(name, ".egg-info") {
					continue
				}
				sub := name
				if rel != "" {
					sub = rel + "/" + name
				}
				if err := walk(filepath.Join(abs, name), sub); err != nil {
					return err
				}
			case d.Type().IsRegular():
				if isExcludedFile(name) {
					continue
				}
				full := filepath.Join(abs, name)
				st, err := os.Stat(full)
				if err != nil {
					return err
				}
				if st.Size() > maxBundleFileBytes {
					continue
				}
				body, err := os.ReadFile(full)
				if err != nil {
					return err
				}
				prefix := ""
				if rel != "" {
					prefix = rel + "/"
				}
				out = append(out, TarEntry{Name: id + "/worker/" + prefix + name, Body: body})
			}
		}
		return nil
	}
	return out, walk(srcDir, "")
}

func generateDockerfile(module string) string {
	return `# Auto-generated by StreamHub Studio export — standalone worker image.
# Rebuild after editing worker/ or worker/requirements.txt.
FROM python:3.11-slim

WORKDIR /app

# Runtime libs the CV workers rely on: glib for opencv-python-headless, ffmpeg
# for HLS reads + evidence clips, ca-certificates for HTTPS callbacks.
RUN apt-get update && apt-get install -y --no-install-recommends \
        ca-certificates ffmpeg libglib2.0-0 \
    && rm -rf /var/lib/apt/lists/*

# Dependencies first so the heavy pip layer stays cached across code edits.
COPY worker/requirements.txt ./requirements.txt
RUN pip install --no-cache-dir --upgrade pip \
    && pip install --no-cache-dir -r requirements.txt

# Worker source.
COPY worker/ ./

CMD ["python", "-m", "` + module + `"]
`
}

func generateCompose(id string) string {
	return `# Auto-generated by StreamHub Studio export.
# Copy .env.example to .env, fill it in, then: docker compose up --build
services:
  ` + id + `:
    build: .
    env_file: .env
    restart: unless-stopped
`
}

func classifyEnv(key, value string) (string, string) {
	switch {
	case key == "PYTHONPATH":
		return "/app", "Container workdir holding the worker package."
	case strings.HasSuffix(key, "_HLS_DIR"):
		return "", "Off-host: leave EMPTY so the worker falls back to *_PUBLIC_BASE. The " +
			"shared HLS disk only exists on the StreamHub host, not on yours."
	case strings.HasSuffix(key, "_PUBLIC_BASE"):
		return placeholderPublicBase, "Base URL of the StreamHub server this worker pulls HLS from " +
			"(it appends /hls/<app>/<room>/index.m3u8)."
	case strings.HasSuffix(key, "_LIVEKIT_URL"):
		return placeholderLivekit, "Only needed if the worker subscribes to LiveKit directly; HLS is the " +
			"normal input."
	case strings.HasSuffix(key, "_CALLBACK_URL"):
		return "", "Your HTTPS endpoint to receive this app’s events (POST). See the " +
			"README for the X-StreamHub-Signature HMAC plane."
	case strings.HasSuffix(key, "_CALLBACK_SECRET"):
		return "", "Shared secret: events are signed X-StreamHub-Signature: sha256=<HMAC-" +
			"SHA256 of the raw body>. Set your own; verify it on your endpoint."
	case secretKeyRe.MatchString(key):
		return "", "Secret — set your own; never commit it."
	}
	return value, ""
}

// orderedEnv collapses duplicate keys the way a JS object would (first
// position, last value).
func orderedEnv(env []EnvVar) []EnvVar {
	idx := map[string]int{}
	var out []EnvVar
	for _, e := range env {
		if i, ok := idx[e.Key]; ok {
			out[i].Value = e.Value
			continue
		}
		idx[e.Key] = len(out)
		out = append(out, e)
	}
	return out
}

func generateEnvExample(meta *Meta, id string, env []EnvVar, getenv func(string) string) string {
	lines := []string{
		"# .env.example — " + meta.Name + " (standalone worker exported from StreamHub Studio)",
		"#",
		"# Copy to .env and fill in the blanks. NEVER commit your real .env.",
		"# Every value below is a placeholder — no real host, token or secret is embedded.",
		"",
		"# --- Framework identity ---",
		"STREAMHUB_APP=" + placeholderApp,
		"STREAMHUB_PLUGIN_ID=" + id,
		"",
		"# --- Worker configuration ---",
	}
	for _, e := range orderedEnv(env) {
		value, comment := classifyEnv(e.Key, e.Value)
		if comment != "" {
			lines = append(lines, "# "+comment)
		}
		lines = append(lines, e.Key+"="+value)
	}
	lines = append(lines, "")
	text := strings.Join(lines, "\n")
	if real := strings.TrimSpace(getenv("PUBLIC_BASE_URL")); real != "" && real != placeholderPublicBase {
		text = strings.ReplaceAll(text, real, placeholderPublicBase)
	}
	return text
}

