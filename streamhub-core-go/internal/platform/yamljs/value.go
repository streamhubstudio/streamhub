// Package yamljs is a Go port of the js-yaml 4.x behaviour the Node core
// relies on: yaml.load(text) with the DEFAULT_SCHEMA and
// yaml.dump(obj, { lineWidth }). The goal is byte-identical config.yaml files
// between the Node and Go cores and the same JS value tree on load.
//
// Values follow JS semantics:
//
//	nil         JS null
//	bool        boolean
//	float64     number (every YAML int/float; NaN, ±Inf and -0 included)
//	string      string
//	time.Time   Date (implicit !!timestamp)
//	[]any       array
//	*Map        plain object (JS property order)
//	Undefined   undefined (what a missing key reads as)
//
// The port follows node_modules/js-yaml/lib (4.3.0) of streamhub-core; the
// golden vectors in testdata/ are generated by that exact copy.
package yamljs

import (
	"bytes"
	"encoding/json"
	"fmt"
	"math"
	"sort"
	"strconv"
	"time"
	"unicode/utf8"
)

// undefinedT is the type of Undefined.
type undefinedT struct{}

// MarshalJSON renders undefined as null (JSON has no undefined; a *Map skips
// such pairs itself, like JSON.stringify).
func (undefinedT) MarshalJSON() ([]byte, error) { return []byte("null"), nil }

// Undefined is JS undefined: the value of a missing key, and what Load
// returns for an empty / comment-only document.
var Undefined any = undefinedT{}

// IsUndefined reports whether v is Undefined.
func IsUndefined(v any) bool { _, ok := v.(undefinedT); return ok }

// Map is a JS plain object: string keys with JS property-order semantics.
// Keys that are canonical array indices ("0".."4294967294") iterate first in
// ascending numeric order, then every other key in insertion order.
// The zero value is not usable; use NewMap.
type Map struct {
	keys []string // insertion order (all keys)
	vals map[string]any
}

// NewMap returns an empty object.
func NewMap() *Map { return &Map{vals: map[string]any{}} }

// Len is Object.keys(m).length.
func (m *Map) Len() int { return len(m.keys) }

// Has is Object.prototype.hasOwnProperty.call(m, k).
func (m *Map) Has(k string) bool { _, ok := m.vals[k]; return ok }

// Lookup returns the value stored under k and whether k is present.
func (m *Map) Lookup(k string) (any, bool) { v, ok := m.vals[k]; return v, ok }

// Get is m[k]: Undefined when k is absent.
func (m *Map) Get(k string) any {
	if v, ok := m.vals[k]; ok {
		return v
	}
	return Undefined
}

// Set is m[k] = v. An existing key keeps its position.
func (m *Map) Set(k string, v any) {
	if _, ok := m.vals[k]; !ok {
		m.keys = append(m.keys, k)
	}
	m.vals[k] = v
}

// Delete is delete m[k].
func (m *Map) Delete(k string) {
	if _, ok := m.vals[k]; !ok {
		return
	}
	delete(m.vals, k)
	for i, x := range m.keys {
		if x == k {
			m.keys = append(m.keys[:i:i], m.keys[i+1:]...)
			break
		}
	}
}

// Keys is Object.keys(m): array-index keys ascending, then insertion order.
func (m *Map) Keys() []string {
	var idx []string
	var rest []string
	for _, k := range m.keys {
		if _, ok := arrayIndex(k); ok {
			idx = append(idx, k)
		} else {
			rest = append(rest, k)
		}
	}
	if len(idx) == 0 {
		return rest
	}
	sort.Slice(idx, func(i, j int) bool {
		a, _ := arrayIndex(idx[i])
		b, _ := arrayIndex(idx[j])
		return a < b
	})
	return append(idx, rest...)
}

// Clone is a shallow copy ({ ...m }).
func (m *Map) Clone() *Map {
	c := &Map{keys: append([]string(nil), m.keys...), vals: make(map[string]any, len(m.vals))}
	for k, v := range m.vals {
		c.vals[k] = v
	}
	return c
}

// arrayIndex reports whether k is a canonical array index (ToString(ToUint32(k))
// === k and != 2^32-1) and returns its numeric value.
func arrayIndex(k string) (uint32, bool) {
	if k == "" || len(k) > 10 || (len(k) > 1 && k[0] == '0') {
		return 0, false
	}
	for i := 0; i < len(k); i++ {
		if k[i] < '0' || k[i] > '9' {
			return 0, false
		}
	}
	n, err := strconv.ParseUint(k, 10, 64)
	if err != nil || n > math.MaxUint32-1 {
		return 0, false
	}
	return uint32(n), true
}

// DeepClone copies every *Map and []any reachable from v (structuredClone for
// the value model); scalars are returned as-is.
func DeepClone(v any) any {
	switch x := v.(type) {
	case *Map:
		if x == nil {
			return x
		}
		c := &Map{keys: append([]string(nil), x.keys...), vals: make(map[string]any, len(x.vals))}
		for k, e := range x.vals {
			c.vals[k] = DeepClone(e)
		}
		return c
	case []any:
		if x == nil {
			return x
		}
		c := make([]any, len(x))
		for i, e := range x {
			c[i] = DeepClone(e)
		}
		return c
	}
	return v
}

// MarshalJSON emits the object like JSON.stringify: keys in Keys() order,
// Undefined pairs skipped, NaN/±Inf as null, Dates as ISO strings.
func (m *Map) MarshalJSON() ([]byte, error) {
	var buf bytes.Buffer
	if err := writeJSON(&buf, m); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// UnmarshalJSON is JSON.parse into an object (order preserved, numbers as
// float64, nested objects as *Map).
func (m *Map) UnmarshalJSON(data []byte) error {
	v, err := ParseJSON(data)
	if err != nil {
		return err
	}
	src, ok := v.(*Map)
	if !ok {
		return fmt.Errorf("yamljs: JSON value is not an object")
	}
	*m = *src
	return nil
}

// Stringify is JSON.stringify(v) for the value model (no indentation).
// Top-level Undefined yields "null".
func Stringify(v any) (string, error) {
	var buf bytes.Buffer
	if err := writeJSON(&buf, v); err != nil {
		return "", err
	}
	return buf.String(), nil
}

// writeJSON appends the JSON.stringify rendering of v.
func writeJSON(buf *bytes.Buffer, v any) error {
	switch x := v.(type) {
	case nil, undefinedT:
		buf.WriteString("null")
	case bool:
		buf.WriteString(strconv.FormatBool(x))
	case float64:
		if math.IsNaN(x) || math.IsInf(x, 0) {
			buf.WriteString("null")
		} else {
			buf.WriteString(JSNumberString(x))
		}
	case string:
		writeJSONString(buf, x)
	case time.Time:
		writeJSONString(buf, isoString(x))
	case *Map:
		if x == nil {
			buf.WriteString("null")
			return nil
		}
		buf.WriteByte('{')
		first := true
		for _, k := range x.Keys() {
			e := x.vals[k]
			if IsUndefined(e) {
				continue
			}
			if !first {
				buf.WriteByte(',')
			}
			first = false
			writeJSONString(buf, k)
			buf.WriteByte(':')
			if err := writeJSON(buf, e); err != nil {
				return err
			}
		}
		buf.WriteByte('}')
	case []any:
		buf.WriteByte('[')
		for i, e := range x {
			if i > 0 {
				buf.WriteByte(',')
			}
			if err := writeJSON(buf, e); err != nil {
				return err
			}
		}
		buf.WriteByte(']')
	default:
		if f, ok := toFloat(v); ok {
			return writeJSON(buf, f)
		}
		b, err := json.Marshal(v)
		if err != nil {
			return err
		}
		buf.Write(b)
	}
	return nil
}

// writeJSONString quotes s like JSON.stringify (no HTML escaping, raw
// U+2028/U+2029, lowercase \u00xx for other control characters).
func writeJSONString(buf *bytes.Buffer, s string) {
	const hex = "0123456789abcdef"
	buf.WriteByte('"')
	for i := 0; i < len(s); {
		c := s[i]
		if c >= utf8.RuneSelf {
			r, size := utf8.DecodeRuneInString(s[i:])
			buf.WriteRune(r)
			i += size
			continue
		}
		switch c {
		case '"':
			buf.WriteString(`\"`)
		case '\\':
			buf.WriteString(`\\`)
		case '\b':
			buf.WriteString(`\b`)
		case '\f':
			buf.WriteString(`\f`)
		case '\n':
			buf.WriteString(`\n`)
		case '\r':
			buf.WriteString(`\r`)
		case '\t':
			buf.WriteString(`\t`)
		default:
			if c < 0x20 {
				buf.WriteString(`\u00`)
				buf.WriteByte(hex[c>>4])
				buf.WriteByte(hex[c&15])
			} else {
				buf.WriteByte(c)
			}
		}
		i++
	}
	buf.WriteByte('"')
}

// ParseJSON is JSON.parse into the value model: objects become *Map (JS key
// order), arrays []any, numbers float64.
func ParseJSON(data []byte) (any, error) {
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.UseNumber()
	v, err := parseJSONValue(dec)
	if err != nil {
		return nil, err
	}
	if _, err := dec.Token(); err == nil {
		return nil, fmt.Errorf("yamljs: unexpected data after JSON value")
	}
	return v, nil
}

func parseJSONValue(dec *json.Decoder) (any, error) {
	tok, err := dec.Token()
	if err != nil {
		return nil, err
	}
	switch t := tok.(type) {
	case json.Delim:
		switch t {
		case '{':
			m := NewMap()
			for dec.More() {
				kt, err := dec.Token()
				if err != nil {
					return nil, err
				}
				v, err := parseJSONValue(dec)
				if err != nil {
					return nil, err
				}
				m.Set(kt.(string), v) // JSON.parse: a later duplicate wins in place
			}
			_, err := dec.Token()
			return m, err
		case '[':
			arr := []any{}
			for dec.More() {
				v, err := parseJSONValue(dec)
				if err != nil {
					return nil, err
				}
				arr = append(arr, v)
			}
			_, err := dec.Token()
			return arr, err
		}
		return nil, fmt.Errorf("yamljs: unexpected JSON delimiter %v", t)
	case json.Number:
		f, err := strconv.ParseFloat(string(t), 64)
		if err != nil && !isRangeErr(err) {
			return nil, err
		}
		return f, nil
	default:
		return t, nil // nil, bool, string
	}
}

func isRangeErr(err error) bool {
	ne, ok := err.(*strconv.NumError)
	return ok && ne.Err == strconv.ErrRange
}

// toFloat widens Go numeric kinds to a JS number.
func toFloat(v any) (float64, bool) {
	switch n := v.(type) {
	case float64:
		return n, true
	case float32:
		return float64(n), true
	case int:
		return float64(n), true
	case int8:
		return float64(n), true
	case int16:
		return float64(n), true
	case int32:
		return float64(n), true
	case int64:
		return float64(n), true
	case uint:
		return float64(n), true
	case uint8:
		return float64(n), true
	case uint16:
		return float64(n), true
	case uint32:
		return float64(n), true
	case uint64:
		return float64(n), true
	}
	return 0, false
}
